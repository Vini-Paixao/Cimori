impl PillRenderer {
    pub(super) fn provider_logo(&mut self, id: &str, x: f32, y: f32, size: f32) {
        let is_claude = id.to_lowercase().contains("claude");
        let path = if is_claude { claude() } else { openai() };
        let mut paint = Paint::default();
        paint.anti_alias = true;
        paint.set_color(if is_claude {
            Color::from_rgba8(217, 119, 87, 255)
        } else {
            white()
        });
        self.layer.fill_path(
            &path,
            &paint,
            FillRule::Winding,
            Transform::from_scale(size * self.scale / 24., size * self.scale / 24.)
                .post_translate(x * self.scale, y * self.scale),
            None,
        );
    }
}
